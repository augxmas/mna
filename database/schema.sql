CREATE DATABASE IF NOT EXISTS siam_deal CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE siam_deal;

CREATE TABLE users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  role ENUM('MEMBER','BROKER','ADMIN') NOT NULL DEFAULT 'MEMBER',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE listings (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  owner_id BIGINT UNSIGNED NOT NULL,
  broker_id BIGINT UNSIGNED NULL,
  type ENUM('REAL_ESTATE','COMPANY') NOT NULL,
  status ENUM('SUBMITTED','IN_REVIEW','PUBLISHED','REJECTED','CLOSED') NOT NULL DEFAULT 'SUBMITTED',
  title VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  price_thb DECIMAL(18,2) NOT NULL,
  province VARCHAR(80) NOT NULL,
  district VARCHAR(80) NOT NULL,
  address_private VARCHAR(255) NULL,
  latitude DECIMAL(10,7) NULL,
  longitude DECIMAL(10,7) NULL,
  published_at DATETIME NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (owner_id) REFERENCES users(id),
  FOREIGN KEY (broker_id) REFERENCES users(id),
  INDEX idx_listing_search (status, type, province, price_thb)
);

CREATE TABLE inquiries (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  listing_id BIGINT UNSIGNED NOT NULL,
  member_id BIGINT UNSIGNED NOT NULL,
  message TEXT NOT NULL,
  status ENUM('NEW','CONTACTED','CLOSED') NOT NULL DEFAULT 'NEW',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (listing_id) REFERENCES listings(id),
  FOREIGN KEY (member_id) REFERENCES users(id)
);

CREATE TABLE deal_reviews (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  listing_id BIGINT UNSIGNED NOT NULL UNIQUE,
  author_id BIGINT UNSIGNED NOT NULL,
  rating TINYINT UNSIGNED NOT NULL,
  content TEXT NOT NULL,
  is_published BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (listing_id) REFERENCES listings(id),
  FOREIGN KEY (author_id) REFERENCES users(id),
  CHECK (rating BETWEEN 1 AND 5)
);
